/**
 * Посадочные страницы каталога под поисковые кластеры Яндекса.
 *
 * Единственный источник данных для динамической страницы `pages/[landing].vue`:
 * мета-теги, заголовки, вводный текст, состав товарных позиций из
 * `priceListProducts`, FAQ-блок (микроразметка FAQPage) и перекрёстные ссылки.
 * Маршруты этих страниц дублируются в `utils/seo-routes.ts` для sitemap
 * и пререндера.
 */
export interface SeoLandingFaq {
  /** Вопрос — формулировка, близкая к реальному поисковому запросу. */
  question: string
  /** Фактический ответ без обещаний, которые не подтверждены владельцем. */
  answer: string
}

export interface SeoLanding {
  /** Слаг страницы: `/<slug>` — латиница, как в остальных ЧПУ сайта. */
  slug: string
  /** Содержимое тега `<title>`; суффикс бренда добавляет titleTemplate. */
  title: string
  /** Meta description с гео-вхождениями и ценой «от». */
  metaDescription: string
  /** Заголовок Open Graph. */
  ogTitle: string
  /** Описание Open Graph. */
  ogDescription: string
  /** Изображение Open Graph — путь в `public/images`. */
  ogImage: string
  /** Ярлык-надзаголовок над H1. */
  eyebrow: string
  /** Заголовок H1 страницы. */
  h1: string
  /** Вводные абзацы под H1. */
  intro: string[]
  /** Идентификаторы позиций из `priceListProducts` для блока цен. */
  productIds: string[]
  /** Заголовок и абзацы текстового SEO-блока. */
  details: {
    heading: string
    paragraphs: string[]
  }
  /** Вопросы и ответы; выводятся на странице и в разметке FAQPage. */
  faq: SeoLandingFaq[]
  /** Перекрёстные ссылки на соседние посадочные и разделы. */
  related: { label: string, to: string }[]
}


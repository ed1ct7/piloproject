/**
 * Посадочные страницы каталога под поисковые кластеры Яндекса.
 *
 * Единственный источник данных для динамической страницы `pages/[landing].vue`:
 * мета-теги, заголовки, вводный текст, подводка к прайсу `priceIntro`, состав
 * товарных позиций из `priceListProducts`, практический блок `practice`,
 * аргументы `whyUs` с гео-абзацем `geoParagraph`, FAQ-блок (микроразметка
 * FAQPage) и перекрёстные ссылки. Общим для всех посадочных остаётся только
 * порядок оформления заказа — константа `landingOrderSteps`; остальные тексты
 * пишутся под конкретный товар, чтобы страницы не пересекались по содержимому.
 * Маршруты этих страниц дублируются в `utils/seo-routes.ts` для sitemap
 * и пререндера.
 */
export interface SeoLandingFaq {
  /** Вопрос — формулировка, близкая к реальному поисковому запросу. */
  question: string
  /** Фактический ответ без обещаний, которые не подтверждены владельцем. */
  answer: string
}

/**
 * Шаг оформления заказа в блоке «Как заказать».
 * @note порядок работы одинаков для всех посадочных, поэтому шаги вынесены
 *       в общую константу `landingOrderSteps`
 */
export interface LandingOrderStep {
  /** Порядковый номер шага в вёрстке: `01`, `02`, `03`. */
  number: string
  /** Короткий заголовок шага. */
  title: string
  /** Описание шага без сроков и обещаний, не подтверждённых владельцем. */
  text: string
}

/** Пункт блока «Почему у нас» — только подтверждённые факты о производстве. */
export interface LandingAdvantage {
  /** Заголовок пункта. */
  title: string
  /** Пояснение в одно-два предложения. */
  text: string
}

export interface SeoLanding {
  /** Слаг страницы: `/<slug>` — латиница, как в остальных ЧПУ сайта. */
  slug: string
  /** Содержимое тега `<title>`; суффикс бренда добавляет titleTemplate. */
  title: string
  /** Meta description с гео-вхождениями и ценой «от». */
  metaDescription: string
  /** Заголовок Open Graph. */
  ogTitle: string
  /** Описание Open Graph. */
  ogDescription: string
  /** Изображение Open Graph — путь в `public/images`. */
  ogImage: string
  /** Ярлык-надзаголовок над H1. */
  eyebrow: string
  /** Заголовок H1 страницы. */
  h1: string
  /** Вводные абзацы под H1. */
  intro: string[]
  /** Идентификаторы позиций из `priceListProducts` для блока цен. */
  productIds: string[]
  /** Абзац-подводка под H2 «Позиции и цены»: что в списке и откуда цены. */
  priceIntro: string
  /** Практический блок: как считать объём и что назвать менеджеру. */
  practice: {
    heading: string
    paragraphs: string[]
  }
  /** Заголовок и абзацы текстового SEO-блока. */
  details: {
    heading: string
    paragraphs: string[]
  }
  /** Четыре аргумента блока «Почему у нас», привязанные к товару страницы. */
  whyUs: LandingAdvantage[]
  /**
   * Гео-абзац под блоком «Почему у нас».
   * @note каждый абзац обязан содержать формулировку «пилорама в Ломоносовском
   *       районе» — так запрос выглядит в статистике Яндекс.Вебмастера;
   *       населённые пункты берутся строго из `areaServed` в `nuxt.config.ts`
   */
  geoParagraph: string
  /** Вопросы и ответы; выводятся на странице и в разметке FAQPage. */
  faq: SeoLandingFaq[]
  /** Перекрёстные ссылки на соседние посадочные и разделы. */
  related: { label: string, to: string }[]
}


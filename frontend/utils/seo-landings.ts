/**
 * Посадочные страницы каталога под поисковые кластеры Яндекса.
 *
 * Единственный источник данных для динамической страницы `pages/[landing].vue`:
 * мета-теги, заголовки секций `headings`, первый абзац с цифрами `introLead`,
 * вводный текст, подводка к прайсу `priceIntro`, состав товарных позиций из
 * `priceListProducts`, таблица расхода `coverage`, сравнение вариантов
 * `comparison`, сценарии применения `scenarios`, практический блок `practice`,
 * аргументы `whyUs` с гео-абзацем `geoParagraph`, FAQ-блок (микроразметка
 * FAQPage) со ссылками `links` и перекрёстные ссылки `related`. Общим для всех
 * посадочных остаётся только порядок оформления заказа — константа
 * `landingOrderSteps`; остальные тексты, включая заголовки H2, пишутся под
 * конкретный товар, чтобы страницы не пересекались по содержимому.
 * Маршруты этих страниц дублируются в `utils/seo-routes.ts` для sitemap
 * и пререндера.
 */
import { timberNote } from './product-sizes'

export interface SeoLandingFaq {
  /** Вопрос — формулировка, близкая к реальному поисковому запросу. */
  question: string
  /** Фактический ответ без обещаний, которые не подтверждены владельцем. */
  answer: string
  /**
   * Ссылки под ответом; выводятся обычными NuxtLink, без `v-html`.
   * @note единственный способ поставить ссылку из текста посадочной: абзацы
   *       `details`, `practice`, `geoParagraph` и `priceIntro` рендерятся как
   *       обычный текст, HTML внутри них не разбирается
   */
  links?: { label: string, to: string }[]
}

/**
 * Шаг оформления заказа в блоке «Как заказать».
 * @note порядок работы одинаков для всех посадочных, поэтому шаги вынесены
 *       в общую константу `landingOrderSteps`; товарную часть первого шага
 *       добавляет поле `orderHint` конкретной посадочной
 */
export interface LandingOrderStep {
  /** Порядковый номер шага в вёрстке: `01`, `02`, `03`. */
  number: string
  /** Короткий заголовок шага. */
  title: string
  /** Описание шага без сроков и обещаний, не подтверждённых владельцем. */
  text: string
}

/** Пункт блока «Почему у нас» — только подтверждённые факты о производстве. */
export interface LandingAdvantage {
  /** Заголовок пункта. */
  title: string
  /** Пояснение в одно-два предложения. */
  text: string
}

/**
 * Товарные заголовки H2 вместо шаблонных.
 * @note отсутствующие ключи шаблон заменяет своими дефолтами; заполнять их
 *       нужно так, чтобы заголовки отличались между посадочными и отвечали
 *       на запрос, а не повторяли «Позиции и цены» на всех пяти страницах
 */
export interface SeoLandingHeadings {
  /** H2 блока позиций прайса. */
  prices?: string
  /** H2 секции размеров, расхода и сравнения (`id="sizes"`). */
  sizes?: string
  /** H2 блока «Как заказать». */
  order?: string
  /** H2 блока аргументов о производстве. */
  whyUs?: string
  /** H2 блока вопросов и ответов. */
  faq?: string
  /** H2 CTA-блока внизу страницы. */
  cta?: string
}

/**
 * Таблица расхода материала на площадь.
 * @note значения — нижняя оценка в штуках: считаются по габаритной ширине,
 *       рабочая ширина меньше на шип, поэтому фактический расход выше
 */
export interface SeoLandingCoverage {
  /** Заголовок таблицы. */
  heading: string
  /** Абзац-подводка: как считается расход и откуда цены. */
  intro: string
  /** Заголовки колонок после первой; первая колонка всегда «Площадь, м²». */
  columns: string[]
  /** Строки: площадь обшивки и значения по колонкам. */
  rows: { area: string, values: string[] }[]
  /** Подпись под таблицей — оговорка о нижней оценке и запасе. */
  note?: string
}

/** Сравнение профилей или вариантов материала. */
export interface SeoLandingComparison {
  /** Заголовок таблицы сравнения. */
  heading: string
  /** Заголовки колонок, включая первую — название параметра. */
  columns: string[]
  /** Строки сравнения в порядке вывода. */
  rows: string[][]
  /** Подпись под таблицей. */
  note?: string
}

/** Сценарии применения: заголовок блока и пункты «H3 + абзац». */
export interface SeoLandingScenarios {
  /** Заголовок блока сценариев. */
  heading: string
  /** Пункты: заголовок сценария и абзац под ним. */
  items: { title: string, text: string }[]
}

export interface SeoLanding {
  /** Слаг страницы: `/<slug>` — латиница, как в остальных ЧПУ сайта. */
  slug: string
  /** Содержимое тега `<title>`; суффикс бренда добавляет titleTemplate. */
  title: string
  /** Meta description с гео-вхождениями и ценой «от»; не длиннее 170 знаков. */
  metaDescription: string
  /** Заголовок Open Graph. */
  ogTitle: string
  /** Описание Open Graph. */
  ogDescription: string
  /** Изображение Open Graph — путь в `public/images`. */
  ogImage: string
  /** Ярлык-надзаголовок над H1. */
  eyebrow: string
  /** Заголовок H1 страницы. */
  h1: string
  /** Товарные заголовки H2; отсутствующие берут дефолт из шаблона. */
  headings?: SeoLandingHeadings
  /**
   * Первый абзац под H1 — предложение с ценами и сечениями.
   * @note шаблон рендерит `[introLead, ...intro]` подряд, поэтому `intro[0]`
   *       не должен повторять содержание `introLead`
   */
  introLead?: string
  /** Вводные абзацы под `introLead`. */
  intro: string[]
  /** Идентификаторы позиций из `priceListProducts` для блока цен. */
  productIds: string[]
  /** Абзац-подводка под заголовком блока цен: что в списке и откуда цены. */
  priceIntro: string
  /**
   * Строка под размерными таблицами из `utils/product-sizes.ts`.
   * @note для позиций без отдельной строки в прайсе, например бруса под заказ
   */
  sizeNote?: string
  /** id абзаца `sizeNote` — якорь страницы, например `brus` на `/doska`. */
  sizeNoteId?: string
  /** Таблица расхода материала на площадь. */
  coverage?: SeoLandingCoverage
  /** Сравнение профилей или вариантов материала. */
  comparison?: SeoLandingComparison
  /** Сценарии применения: где и какое сечение берут. */
  scenarios?: SeoLandingScenarios
  /** Практический блок: как считать объём и на что смотреть при выборе. */
  practice: {
    heading: string
    paragraphs: string[]
  }
  /** Заголовок, якорь и абзацы текстового SEO-блока. */
  details: {
    heading: string
    /** Якорь секции, например `sorta` на `/doska`. */
    id?: string
    paragraphs: string[]
  }
  /** Четыре аргумента блока о производстве, привязанные к товару страницы. */
  whyUs: LandingAdvantage[]
  /**
   * Гео-абзац под блоком аргументов: где стоит площадка и куда возят заказы.
   * @note населённые пункты берутся строго из `areaServed` в `nuxt.config.ts`,
   *       но набор и формулировка у каждой посадочной свои — одинаковый
   *       список городов на пяти страницах читается как шаблон
   */
  geoParagraph: string
  /** Что назвать менеджеру — товарный абзац в шаге 01 «Как заказать». */
  orderHint?: string
  /** Вопросы и ответы; выводятся на странице и в разметке FAQPage. */
  faq: SeoLandingFaq[]
  /** Перекрёстные ссылки на соседние посадочные и разделы. */
  related: { label: string, to: string }[]
  /** Абзац CTA-блока без режима работы: режим шаблон дописывает сам. */
  ctaText?: string
}

